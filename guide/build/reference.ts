function weapons(): string {
  const rows = items()
    .filter((i) => i.kind === 'weapon' && isLive(i))
    .map((i) => {
      const f = describeItem(i);
      return [f.name, f.weaponLine ?? '—', f.effects.length > 0 ? f.effects.join('; ') : '—'];
    });
  return ['## 2. Weapons', '', table(['Name', 'WP · Acc · family · range · 2H', 'Riders / on-hit'], rows)].join('\n');
}

function accessories(): string {
  const rows = items()
    .filter((i) => i.kind === 'accessory' && isLive(i))
    .map((i) => {
      const f = describeItem(i);
      return [f.name, f.effects.length > 0 ? f.effects.join('; ') : '—'];
    });
  return ['## 3. Accessories', '', table(['Name', 'Effect'], rows)].join('\n');
}

const ARMOR_SLOT: Record<string, string> = {
  armor: 'body',
  headgear: 'head',
  shield: 'off-hand',
};

function armor(): string {
  const rows = items()
    .filter((i) => (i.kind === 'armor' || i.kind === 'headgear' || i.kind === 'shield') && isLive(i))
    .map((i) => {
      const f = describeItem(i);
      const restriction = f.tierLabel ?? 'universal';
      return [f.name, ARMOR_SLOT[i.kind] ?? i.kind, restriction, f.effects.length > 0 ? f.effects.join('; ') : '—'];
    });
  return ['## 4. Armor — head / body / shield', '', table(['Name', 'Slot', 'Tier', 'Stat mods / riders'], rows)].join('\n');
}

/** A class's restricted-gear access, derived from item restrictions (data-driven). */
function gearAccess(cls: ClassDefinition): string {
  const tiers = new Set<string>();
  for (const i of items()) {
    if (i.classRestrictions?.some((r) => String(r) === String(cls.id))) {
      const label = describeItem(i).tierLabel;
      if (label) tiers.add(label.toLowerCase());
    }
  }
  return tiers.size === 0 ? 'universal' : `universal + ${[...tiers].join('/')}`;
}

function classStatLines(): string {
  const rows = classes().map((cls) => {
    const s = baselineStats(cls.id);
    const ev = cls.evasion;
    const innate = [...cls.freeAbilities]
      .map((id) => catalog().getAbility(id).name)
      .filter((n) => n !== 'Attack');
    return [
      cls.name,
      s.maxHpBase,
      s.maxMpBase,
      s.pa,
      s.ma,
      s.spd,
      70, // Brave — placement default (§1)
      70, // Faith — placement default (§1)
      cls.movement.moveRange,
      cls.movement.jump,
      `${ev.front}/${ev.side}/${ev.back}`,
      gearAccess(cls),
      innate.length > 0 ? innate.join(', ') : '—',
    ];
  });
  return [
    '## 5. Classes — stat lines',
    '',
    '*Brave / Faith are the uniform placement defaults (§1), not per-class values.*',
    '',
    table(
      ['Class', 'HP', 'MP', 'PA', 'MA', 'Spd', 'Brave', 'Faith', 'Move', 'Jump', 'Eva F/S/B', 'Gear access', 'Innate (free)'],
      rows,
    ),
  ].join('\n');
}

function abilities(own: Ownership): string {
  const actives = catalog()
    .abilities()
    .filter((a): a is ActiveAbilityDefinition => a.kind === 'active' && isLive(a));
  const rows = actives.map((a) => {
    const f = describeAbility(a);
    return [
      f.name,
      ownerLabel(String(a.id), own.owners),
      f.capacityCost,
      f.mpCost ?? '—',
      f.range ?? '—',
      f.chargeLabel ?? '—',
      effectCell(a),
    ];
  });
  return [
    '## 6. Abilities (actives)',
    '',
    table(['Ability', 'Class / set', 'Cap', 'MP', 'Range', 'Speed', 'Effect'], rows),
  ].join('\n');
}

function rsmPassives(own: Ownership): string {
  const passives = catalog()
    .abilities()
    .filter((a): a is PassiveAbilityDefinition => a.kind === 'passive' && isLive(a));
  const rows = passives.map((p) => {
    const f = describeAbility(p);
    const native = own.natives.get(String(p.id))?.join(' / ') ?? '—';
    let effect = PASSIVE_EFFECTS[String(p.id)] ?? '⚠ hand-maintain: add effect';
    if (f.trigger) effect = `${effect} — ${f.trigger}`;
    return [f.name, f.bucketLabel, f.capacityCost, native, effect];
  });
  return [
    '## 7. RSM passives',
    '',
    '*Effect column hand-maintained (passive behavior lives in hook code, not data).*',
    '',
    table(['Name', 'Bucket', 'Cost', 'Native', 'Effect'], rows),
  ].join('\n');
}

function statuses(): string {
  const rows = catalog()
    .statusTypes()
    .map((st) => {
      const flags: string[] = [];
      if (st.remedyImmune) flags.push('remedy-immune');
      if (st.controlOverride) flags.push('control-override');
      if (st.controlOverrideImmune) flags.push('charm-immune');
      if (st.removeOnSourceKO) flags.push('removed on source KO');
      // Steal Buffs reads `aiHints.polarity === 'buff'` exactly. Where a
      // status leaves polarity unset, fall back to its tags for the
      // reader's three-way sense (positive → buff, neutral → neither,
      // else → debuff — the engine's default-debuff assumption).
      const tags = st.tags.map(String);
      const polarity =
        st.aiHints?.polarity ??
        (tags.includes('positive')
          ? 'buff'
          : tags.includes('neutral')
            ? 'neither'
            : 'debuff');
      return [
        st.name,
        polarity,
        st.durationMode,
        st.resistanceTag ?? '—',
        st.tags.length > 0 ? st.tags.join(', ') : '—',
        flags.length > 0 ? flags.join('; ') : '—',
      ];
    });
  return [
    '## 8. Statuses',
    '',
    '*Polarity drives Steal Buffs (steals only `buff`, non-equipment) and dispel filters.*',
    '',
    table(['Status', 'Polarity', 'Duration mode', 'Resist tag', 'Tags', 'Flags'], rows),
  ].join('\n');
}

function header(): string {
  return [
    '# Mage War — Planner Content Reference',
    '',
    '> **Generated artifact — do not hand-edit.** Produced by `npm run build:reference`',
    '> (`guide/build/reference.ts`) from the same content catalog the Player\'s Guide imports.',
    '> The schema/contract is `guide/planner-content-reference.md`. §2–§8 and the §1 ruleset',
    '> table are auto-extracted and always true. The §1 *formula* block and the §7 passive',
    '> *effect* column are hand-mirrored from engine handler / hook code (they aren\'t',
    '> extractable as data); each carries a `src/engine/...` pointer and is re-verified when',
    '> the cited system changes. `[verify]` marks a genuinely uncertain cell; ⚠ marks a',
    '> hand-maintained line awaiting an entry.',
    '>',
    '> **Scope:** only team-builder-available content is listed (`availability: \'available\'`).',
    '> Hidden content — system-emitted procs (Discharge Strike, weapon resonances), test',
    '> fixtures, and unhomed/playtest pieces — is excluded, matching the team builder and AI',
    '> generation. A hidden sub-ability still appears by name where a live ability references it.',
  ].join('\n');
}

/** Assemble the full planner reference document. */
export function buildReference(): string {
  const own = computeOwnership();
  return [
    header(),
    systemConstants(),
    weapons(),
    accessories(),
    armor(),
    classStatLines(),
    abilities(own),
    rsmPassives(own),
    statuses(),
  ].join('\n\n---\n\n') + '\n';
}
