// Planner Content Reference — the markdown emitter.
//
// Builds a terse, mechanical-only mirror of the game's content for the
// *planner* thread (a parallel Opus chat that reasons about new content
// without code access). It is the stripped-down sibling of the Player's
// Guide: no flavor, no lore, no prose — numbers and one-line effects.
//
// The schema/contract is `guide/planner-content-reference.md` (the
// planner authored it). This module is the generator that fills it; the
// live output lands in `guide/output/planner-content-reference.md` (a
// gitignored build artifact, regenerated by `npm run build:reference`).
//
// Two kinds of content:
//   - AUTO-EXTRACTED (§2–§8, and part of §1): flows straight from the
//     same catalog the guide imports, via the shared formatters
//     (describeItem / describeAbility) and the data doorway. Always true.
//   - HAND-MIRRORED (the §1 formula block; the §7 passive-effect lines):
//     formulas live in engine handler code, not as extractable data;
//     passive *effects* live in hook code. These carry explicit
//     `src/engine/...` pointers and are re-verified when the relevant
//     system changes (see maintaining.md). Genuinely uncertain cells are
//     marked `[verify]`; a missing curated line shows a loud ⚠ marker
//     rather than a silent gap (per CLAUDE.md: no silent fallbacks).
//
// tsx-safe: imports only data.ts + the two formatters. It must NOT pull
// compose.ts / spread-context.ts (those carry a `?raw` SVG import tsx
// can't resolve). Runs under plain tsx with no Vite (see render-reference.ts).
//
// Read-only with respect to ../src. See guide/CLAUDE.md.

import { catalog, classes, items, baselineStats, defaultRuleset } from './data.ts';
