// --- availability filter ----------------------------------------------
//
// The reference mirrors what a player can actually field: only content
// the team builder surfaces (`availability: 'available'`). `'hidden'`
// content — test fixtures, system-emitted procs (discharge_strike, the
// weapon resonance shifts), homeless/playtest pieces (Strength Ring, the
// Iron armour, Float) — is excluded, matching the team builder and AI
// generation. Hidden sub-abilities still surface by name where a live
// ability references them (e.g. §7 Discharge "retaliate with Discharge
// Strike"); we just don't give them their own rows. Per ADR-0049.
function isLive(def: { readonly availability: string }): boolean {
  return def.availability === 'available';
}

// --- markdown helpers -------------------------------------------------

/** Escape a cell for a GitHub-flavoured markdown table: no raw pipes, no newlines. */
function esc(value: string | number | undefined): string {
  if (value === undefined) return '—';
  return String(value).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim() || '—';
}

/** A markdown table from a header row and body rows. */
function table(headers: ReadonlyArray<string>, rows: ReadonlyArray<ReadonlyArray<string | number>>): string {
  const head = `| ${headers.join(' | ')} |`;
  const sep = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((r) => `| ${r.map(esc).join(' | ')} |`).join('\n');
  return `${head}\n${sep}\n${body}`;
}

/** Join an ability's structured effect descriptors into one terse cell. */
function effectCell(active: ActiveAbilityDefinition): string {
  const facts = describeAbility(active);
  const parts = [...facts.effects];
  if (facts.rollsToHit) parts.push('rolls to hit');
  const augment = ACTIVE_EFFECTS[String(active.id)];
  if (augment) parts.push(augment);
  // A loud marker when the formatter found nothing AND no curated line
  // exists — a visible gap, not a silent blank (per CLAUDE.md).
  return parts.length > 0 ? parts.join('; ') : '⚠ hand-maintain: add effect';
}

// --- ability ownership ------------------------------------------------
//
// Which class(es) surface each ability through their First Action set or
// free abilities — the same view the guide's class spreads take. An
// ability owned by every class (the universal Attack) reads "Universal".

interface Ownership {
  /** ability id → class display names that grant it (free or via command set). */
  readonly owners: ReadonlyMap<string, ReadonlyArray<string>>;
  /** ability id → class display names that grant it *free* (the "native" column). */
  readonly natives: ReadonlyMap<string, ReadonlyArray<string>>;
}

function computeOwnership(): Ownership {
  const owners = new Map<string, string[]>();
  const natives = new Map<string, string[]>();
  for (const cls of classes()) {
    const memberIds = new Set<string>();
    for (const id of cls.freeAbilities) memberIds.add(String(id));
    for (const id of catalog().getCommandSet(cls.firstActionCommandSet).members) {
      memberIds.add(String(id));
    }
    for (const id of memberIds) {
      (owners.get(id) ?? owners.set(id, []).get(id)!).push(cls.name);
    }
    for (const id of cls.freeAbilities) {
      const key = String(id);
      (natives.get(key) ?? natives.set(key, []).get(key)!).push(cls.name);
    }
  }
  return { owners, natives };
}

function ownerLabel(abilityId: string, owners: ReadonlyMap<string, ReadonlyArray<string>>): string {
  const list = owners.get(abilityId);
  if (!list || list.length === 0) return '—';
  if (list.length === classes().length) return 'Universal';
  return list.join(' / ');
}

